// `apply --upgrade` (found by the Vyugate trial). An older kit installed the
// hooks; their checks read `declared`, so buildProposals never ran their
// generators and the newer scripts were never offered. These pin the opt-in
// path: what it offers, what it keeps, what it holds back, and that a plain
// run is unchanged apart from one line.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { emptyManifest, sha256 } from './manifest.mjs';
import { buildPlan, buildProposals, pendingUpgrades, LINT_TOUCHED_PATH, VERIFY_TOUCHED_PATH, REDACT_PATH, BRIEF_PATH } from './propose.mjs';
import { APPLY_USAGE } from './cli.mjs';
import { APPLY, DETECT, git, run, workspaceFixture, manifestOf } from './lifecycle-fixtures.mjs';

const tmp = () => mkdtempSync(join(tmpdir(), 'hk-upg-'));
const STACK = { packages: [{ name: 'app', dir: '.', manifestPath: 'package.json', scripts: ['lint', 'typecheck', 'test'] }], languages: ['typescript'], isWorkspace: false, packageManager: null, ci: [] };
const declared = id => ({ id, step: 9, phase: 2, state: 'declared', decidable: true, evidence: [], proposal: null });
const SENSOR = declared('P2.sensor');

// What an older kit wrote: stamped, and different from today's assets.
const oldScript = step => `#!/usr/bin/env node\n// Generated by kh-harness 0.0.9 (runbook step ${step}). Edit freely — kh-harness will report your changes rather than overwrite them.\n// an older body\n`;
const OLD_REDACT = '// Generated by kh-harness 0.0.9 (shared asset used by the PostToolUse, Stop and SessionStart hooks).\nexport function projectRoot() { return process.cwd(); }\n';

function install(d, entries) {
  const m = emptyManifest('0.0.9');
  for (const [path, contents] of Object.entries(entries)) {
    mkdirSync(join(d, path, '..'), { recursive: true });
    writeFileSync(join(d, path), contents);
    m.files.push({ path, sha256: sha256(contents), step: 9, writtenAt: 'then' });
  }
  return m;
}
const planArgs = (d, manifest, checks = [SENSOR], extra = {}) => ({
  root: d, checks, manifest, kitVersion: '0.2.0', harness: { claudeDir: {} }, stack: STACK, files: [], ...extra,
});

test('UPGRADE-OPT-IN: a declared check yields nothing without --upgrade, exactly as before', () => {
  const d = tmp();
  const m = install(d, { [LINT_TOUCHED_PATH]: oldScript(9), [REDACT_PATH]: OLD_REDACT });
  assert.deepEqual(buildProposals(planArgs(d, m)), []);
});

test('UPGRADE-OPT-IN: files an older kit wrote, unmodified and stamped, are offered — and only files', () => {
  const d = tmp();
  const m = install(d, { [LINT_TOUCHED_PATH]: oldScript(9), [REDACT_PATH]: OLD_REDACT });
  const { proposals, held } = buildPlan(planArgs(d, m, [SENSOR], { upgrade: true }));
  assert.deepEqual(proposals.map(p => p.path), [REDACT_PATH, LINT_TOUCHED_PATH], 'the imported module first, then the script');
  assert.ok(proposals.every(p => p.kind === 'file' && p.upgrade === true), 'no settings patch rides along');
  assert.ok(proposals.every(p => /unmodified since kh-harness wrote it/.test(p.reason)));
  assert.deepEqual(held, []);
  assert.deepEqual(pendingUpgrades(planArgs(d, m)), [REDACT_PATH, LINT_TOUCHED_PATH]);
});

test('UPGRADE-OPT-IN: a declared check never yields a NEW file, even one its generator would write', () => {
  const d = tmp();
  // Only the script is recorded; the shared module is not ours on record.
  const m = install(d, { [LINT_TOUCHED_PATH]: oldScript(9) });
  const { proposals, held } = buildPlan(planArgs(d, m, [SENSOR], { upgrade: true }));
  assert.equal(proposals.find(p => p.path === REDACT_PATH), undefined, 'no new file under --upgrade');
  // …and so the script cannot be updated either: it would import from a
  // module that is not there.
  assert.equal(proposals.length, 0);
  assert.equal(held.length, 1);
  assert.equal(held[0].path, LINT_TOUCHED_PATH);
  assert.match(held[0].reason, /harness-redact\.mjs \(missing\)/);
});

test('UPGRADE-OPT-IN: a file the user edited is kept, and a script that imports it is held, with the reason', () => {
  const d = tmp();
  const m = install(d, { [LINT_TOUCHED_PATH]: oldScript(9), [REDACT_PATH]: OLD_REDACT });
  writeFileSync(join(d, REDACT_PATH), OLD_REDACT + '// my own tweak\n');
  const { proposals, held } = buildPlan(planArgs(d, m, [SENSOR], { upgrade: true }));
  assert.deepEqual(proposals, [], 'neither the edited module nor the script that needs its new version');
  assert.equal(held[0].path, LINT_TOUCHED_PATH);
  assert.match(held[0].reason, /modified since kh-harness wrote it/);
  assert.equal(readFileSync(join(d, REDACT_PATH), 'utf8'), OLD_REDACT + '// my own tweak\n');
});

test('UPGRADE-OPT-IN: an edited hook script is kept while the module it imports is still updated', () => {
  const d = tmp();
  const m = install(d, { [LINT_TOUCHED_PATH]: oldScript(9), [REDACT_PATH]: OLD_REDACT });
  writeFileSync(join(d, LINT_TOUCHED_PATH), oldScript(9) + '// mine now\n');
  const { proposals } = buildPlan(planArgs(d, m, [SENSOR], { upgrade: true }));
  assert.deepEqual(proposals.map(p => p.path), [REDACT_PATH]);
});

test('UPGRADE-OPT-IN: a hash-matching recorded file without the kit stamp is kept', () => {
  const d = tmp();
  const theirs = '// my own module\nexport function projectRoot() { return process.cwd(); }\n';
  const m = install(d, { [REDACT_PATH]: theirs, [LINT_TOUCHED_PATH]: oldScript(9) });
  const { proposals, held } = buildPlan(planArgs(d, m, [SENSOR], { upgrade: true }));
  assert.equal(proposals.find(p => p.path === REDACT_PATH), undefined, 'the manifest alone is forgeable — no stamp, not ours');
  assert.equal(held[0].path, LINT_TOUCHED_PATH);
  assert.match(held[0].reason, /missing the kh-harness stamp/);
});

test('UPGRADE-OPT-IN: a shared module whose new version drops an export the installed one has is held', () => {
  const d = tmp();
  const withExtra = OLD_REDACT + 'export function somethingRemoved() {}\n';
  const m = install(d, { [REDACT_PATH]: withExtra });
  const { proposals, held } = buildPlan(planArgs(d, m, [SENSOR], { upgrade: true }));
  assert.equal(proposals.find(p => p.path === REDACT_PATH), undefined);
  assert.equal(held[0].path, REDACT_PATH);
  assert.match(held[0].reason, /no longer exports somethingRemoved/);
});

test('UPGRADE-OPT-IN: a shell-form registration of an upgraded script is named, never rewritten', () => {
  const d = tmp();
  const m = install(d, { [LINT_TOUCHED_PATH]: oldScript(9), [REDACT_PATH]: OLD_REDACT });
  const harness = { claudeDir: { hookRegistrations: { PostToolUse: [{ script: LINT_TOUCHED_PATH, matcher: 'Edit|Write', form: 'shell' }] } } };
  const { proposals, notes } = buildPlan(planArgs(d, m, [SENSOR], { upgrade: true, harness }));
  assert.equal(notes.length, 1);
  assert.match(notes[0], /shell form/);
  assert.match(notes[0], /needs nothing that registration lacks/);
  assert.match(notes[0], /never edits settings\.json/);
  assert.ok(proposals.every(p => p.kind === 'file'));
  const exec = { claudeDir: { hookRegistrations: { PostToolUse: [{ script: LINT_TOUCHED_PATH, matcher: 'Edit|Write', form: 'exec' }] } } };
  assert.deepEqual(buildPlan(planArgs(d, m, [SENSOR], { upgrade: true, harness: exec })).notes, []);
});

test('UPGRADE-OPT-IN: --upgrade is documented in apply --help', () => {
  assert.match(APPLY_USAGE, /--upgrade/);
});

// --- End to end: a repository an older kit installed into -----------------

/** Install with today's kit, then rewrite the three hook files as an older
 * kit would have left them — stamped, different, and hash-recorded — and
 * commit, so the repository is exactly what a 0.0.9 install looks like. */
function olderInstall() {
  const d = workspaceFixture();
  run(APPLY, d, '--yes');
  const m = manifestOf(d);
  const older = { [LINT_TOUCHED_PATH]: oldScript(9), [VERIFY_TOUCHED_PATH]: oldScript(10), [REDACT_PATH]: OLD_REDACT };
  for (const [path, contents] of Object.entries(older)) {
    writeFileSync(join(d, path), contents);
    m.files.find(f => f.path === path).sha256 = sha256(contents);
  }
  writeFileSync(join(d, '.claude/kh-harness.manifest.json'), JSON.stringify(m, null, 2) + '\n');
  git(d, 'add', '-A');
  git(d, '-c', 'user.email=t@t', '-c', 'user.name=t', 'commit', '-q', '-m', 'older kit');
  return { d, older };
}

test('UPGRADE-E2E: detect and a plain apply say, in one line, that --upgrade would update the older files', () => {
  const { d } = olderInstall();
  const detectOut = run(DETECT, d);
  const line = detectOut.split('\n').filter(l => l.includes('apply --upgrade'));
  assert.equal(line.length, 1, detectOut);
  assert.match(line[0], /^3 files kh-harness wrote are older than this kit/);
  const applyOut = run(APPLY, d);
  assert.equal(applyOut.split('\n').filter(l => l.includes('apply --upgrade')).length, 1, applyOut);
  assert.equal(git(d, 'status', '--porcelain', '--untracked-files=no'), '', 'neither wrote a tracked file');
});

test('UPGRADE-E2E: older files are upgraded, settings.json is not touched, nothing is written without --yes, and a second run is a no-op', () => {
  const { d, older } = olderInstall();
  const settingsBefore = readFileSync(join(d, '.claude/settings.json'), 'utf8');

  const dry = run(APPLY, d, '--upgrade');
  assert.match(dry, /3 files to upgrade \(--upgrade\)/);
  assert.match(dry, /Dry run — nothing written/);
  for (const [path, contents] of Object.entries(older)) assert.equal(readFileSync(join(d, path), 'utf8'), contents, `${path} untouched by a dry run`);
  assert.equal(git(d, 'status', '--porcelain', '--untracked-files=no'), '');

  const wet = run(APPLY, d, '--upgrade', '--yes');
  for (const path of Object.keys(older)) assert.match(wet, new RegExp(`wrote\\s+${path.replace(/[.]/g, '\\.')}`));
  assert.doesNotMatch(wet, /patched/, 'no settings patch under --upgrade');
  assert.equal(readFileSync(join(d, '.claude/settings.json'), 'utf8'), settingsBefore);
  const m = manifestOf(d);
  for (const path of Object.keys(older)) {
    const now = readFileSync(join(d, path), 'utf8');
    assert.notEqual(now, older[path]);
    assert.equal(m.files.find(f => f.path === path).sha256, sha256(now), `${path} re-recorded`);
  }
  // The session brief was already current, so it was not rewritten.
  assert.doesNotMatch(wet, new RegExp(`wrote\\s+${BRIEF_PATH.replace(/[.]/g, '\\.')}`));

  const again = run(APPLY, d, '--upgrade', '--yes');
  assert.doesNotMatch(again, /^wrote/m);
  assert.match(again, /--upgrade found nothing to update/);
  assert.doesNotMatch(run(DETECT, d), /apply --upgrade/, 'and detect no longer mentions it');
});

test('UPGRADE-E2E: a user-edited file is kept through --upgrade --yes', () => {
  const { d } = olderInstall();
  const mine = oldScript(10) + '// my own change\n';
  writeFileSync(join(d, VERIFY_TOUCHED_PATH), mine);
  git(d, '-c', 'user.email=t@t', '-c', 'user.name=t', 'commit', '-q', '-am', 'my edit');
  const out = run(APPLY, d, '--upgrade', '--yes');
  assert.equal(readFileSync(join(d, VERIFY_TOUCHED_PATH), 'utf8'), mine);
  assert.match(out, /kept\s+\.claude\/scripts\/verify-touched\.mjs \(modified since kh-harness wrote it/);
  assert.match(out, /wrote\s+\.claude\/scripts\/lint-touched\.mjs/);
});
