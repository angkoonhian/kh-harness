test('a contract file reached through a link is unreadable, and names the link', { skip: noLinks }, () => {
  const outside = tempDir('hk-contract-outside-');
  writeAt(join(outside, 'kh-harness/contract.json'), TEXT);

  const fileLink = tempDir();
  mkdirSync(join(fileLink, '.claude/kh-harness'), { recursive: true });
  symlinkSync(join(outside, 'kh-harness/contract.json'), join(fileLink, CONTRACT_PATH), 'file');
  assert.deepEqual(contractEvidence(fileLink, TEXT), { state: 'unreadable', link: CONTRACT_PATH });

  const dirLink = tempDir();
  mkdirSync(join(dirLink, '.claude'));
  symlinkSync(join(outside, 'kh-harness'), join(dirLink, '.claude/kh-harness'), 'dir');
  assert.deepEqual(contractEvidence(dirLink, TEXT), { state: 'unreadable', link: '.claude/kh-harness' });

  const claudeLink = tempDir();
  symlinkSync(outside, join(claudeLink, '.claude'), 'dir');
  assert.deepEqual(contractEvidence(claudeLink, TEXT), { state: 'unreadable', link: '.claude' });

  // A .claude kept elsewhere through which no contract file is reached is
  // no contract file, as the extensions loader reads a .claude link.
  const emptyLink = tempDir();
  symlinkSync(tempDir('hk-contract-outside-'), join(emptyLink, '.claude'), 'dir');
  assert.deepEqual(contractEvidence(emptyLink, TEXT), { state: 'absent', link: '.claude' }, 'and names the link, since no contract file can be written through it');

  // The repository root itself may be reached through a link.
  const real = withContract(TEXT);
  const rootLink = join(tempDir(), 'repo');
  symlinkSync(real, rootLink, 'dir');
  assert.deepEqual(contractEvidence(rootLink, TEXT), ok);
});

