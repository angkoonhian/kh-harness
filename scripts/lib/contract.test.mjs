import { test, after } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import { constants, mkdirSync, mkdtempSync, rmSync, symlinkSync, unlinkSync, writeFileSync } from 'node:fs';
import { syncBuiltinESMExports } from 'node:module';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';

import { CONTRACT, CONTRACT_PATH, contractEvidence, contractFileText } from './contract.mjs';
import { stampVersion } from './render.mjs';

const dirs = [];
after(() => {
  for (const d of dirs) rmSync(d, { recursive: true, force: true });
});
function tempDir(prefix = 'hk-contract-') {
  const d = mkdtempSync(join(tmpdir(), prefix));
  dirs.push(d);
  return d;
}
function writeAt(path, text) {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, text);
}
/** A repository whose contract file holds `text`. */
function withContract(text) {
  const root = tempDir();
  writeAt(join(root, CONTRACT_PATH), text);
  return root;
}
// A link needs elevation on win32, and there is no O_NOFOLLOW there.
const noLinks = process.platform === 'win32' ? 'win32 needs elevation to make a link' : false;

// What a kit writes: one file it speaks for, with its hash, built at run
// time.
const FILES = Object.freeze({ '.claude/scripts/b.mjs': 'b'.repeat(64), '.claude/scripts/a.mjs': 'a'.repeat(64) });
const TEXT = contractFileText('0.2.0', FILES);
const ok = { state: 'ok', contract: 1, kitWritten: true };

test('the contract file holds the contract number, the kit stamp and the files it speaks for with their hashes', () => {
  const file = JSON.parse(TEXT);
  assert.deepEqual(Object.keys(file), ['contract', 'generatedBy', 'files']);
  assert.equal(file.contract, 1);
  assert.equal(CONTRACT, 1);
  assert.equal(CONTRACT_PATH, '.claude/kh-harness/contract.json');
  assert.ok(file.generatedBy.startsWith('Generated by kh-harness 0.2.0 ('));
  assert.deepEqual(Object.entries(file.files), Object.entries(FILES), 'in the order given');
  assert.equal(stampVersion(TEXT), '0.2.0');
  assert.ok(TEXT.endsWith('}\n'));
});

test('contractEvidence reads the number, says whether the file is the one this kit writes, and calls anything else unreadable', () => {
  assert.deepEqual(contractEvidence(tempDir(), TEXT), { state: 'absent' });
  assert.deepEqual(contractEvidence(withContract(TEXT), TEXT), ok);
  assert.deepEqual(contractEvidence(withContract(TEXT.replace(/\n/g, '\r\n')), TEXT), ok, 'line endings aside');
  assert.deepEqual(contractEvidence(withContract(TEXT.replace('"contract": 1', '"contract": 2')), TEXT), { state: 'ok', contract: 2, kitWritten: false }, 'an edited number');
  assert.deepEqual(contractEvidence(withContract(TEXT.replace('a'.repeat(64), 'c'.repeat(64))), TEXT), { ...ok, kitWritten: false }, 'an edited hash');
  assert.deepEqual(contractEvidence(withContract('{ "contract": 1 }'), TEXT), { ...ok, kitWritten: false }, 'no list');
  for (const text of ['{ not json', '[]', '{}', '{"contract":"1"}', '{"contract":1.5}', '{"contract":0}', 'null', '1', '{"contract":1e300}', `{"contract":${2 ** 53 + 1}}`]) {
    assert.deepEqual(contractEvidence(withContract(text), TEXT), { state: 'unreadable' }, text);
  }
  assert.deepEqual(contractEvidence(withContract(`{"contract":1,"pad":"${'x'.repeat(2 * 1024 * 1024)}"}`), TEXT), { state: 'unreadable' }, 'a 2 MiB file');
  const directory = tempDir();
  mkdirSync(join(directory, CONTRACT_PATH), { recursive: true });
  assert.deepEqual(contractEvidence(directory, TEXT), { state: 'unreadable' }, 'a directory');
});

test('a .claude or .claude/kh-harness that is not a directory is named, since no contract file can be there', () => {
  const kitDirIsFile = tempDir();
  writeAt(join(kitDirIsFile, '.claude/kh-harness'), '');
  assert.deepEqual(contractEvidence(kitDirIsFile, TEXT), { state: 'unreadable', notDirectory: '.claude/kh-harness' });
  const claudeIsFile = tempDir();
  writeAt(join(claudeIsFile, '.claude'), '');
  assert.deepEqual(contractEvidence(claudeIsFile, TEXT), { state: 'unreadable', notDirectory: '.claude' });
});

test('a contract file reached through a link is unreadable, and names the link', { skip: noLinks }, () => {
  const outside = tempDir('hk-contract-outside-');
  writeAt(join(outside, 'kh-harness/contract.json'), TEXT);

  const fileLink = tempDir();
  mkdirSync(join(fileLink, '.claude/kh-harness'), { recursive: true });
  symlinkSync(join(outside, 'kh-harness/contract.json'), join(fileLink, CONTRACT_PATH), 'file');
  assert.deepEqual(contractEvidence(fileLink, TEXT), { state: 'unreadable', link: CONTRACT_PATH });

  const dirLink = tempDir();
  mkdirSync(join(dirLink, '.claude'));
  symlinkSync(join(outside, 'kh-harness'), join(dirLink, '.claude/kh-harness'), 'dir');
  assert.deepEqual(contractEvidence(dirLink, TEXT), { state: 'unreadable', link: '.claude/kh-harness' });

  const claudeLink = tempDir();
  symlinkSync(outside, join(claudeLink, '.claude'), 'dir');
  assert.deepEqual(contractEvidence(claudeLink, TEXT), { state: 'unreadable', link: '.claude' });

  // A .claude kept elsewhere through which no contract file is reached is
  // no contract file, as the extensions loader reads a .claude link.
  const emptyLink = tempDir();
  symlinkSync(tempDir('hk-contract-outside-'), join(emptyLink, '.claude'), 'dir');
  assert.deepEqual(contractEvidence(emptyLink, TEXT), { state: 'absent' });

  // The repository root itself may be reached through a link.
  const real = withContract(TEXT);
  const rootLink = join(tempDir(), 'repo');
  symlinkSync(real, rootLink, 'dir');
  assert.deepEqual(contractEvidence(rootLink, TEXT), ok);
});

test('a contract file swapped for a link between its lstat and its open is not followed', { skip: noLinks || (constants.O_NOFOLLOW === undefined && 'this platform has no O_NOFOLLOW') }, (t) => {
  const outside = tempDir('hk-contract-outside-');
  writeAt(join(outside, 'contract.json'), '{ "contract": 7 }');
  const root = withContract(TEXT);
  const path = join(root, CONTRACT_PATH);
  const lstat = fs.lstatSync;
  t.after(() => { fs.lstatSync = lstat; syncBuiltinESMExports(); });
  fs.lstatSync = (p, ...rest) => {
    const st = lstat(p, ...rest);
    if (p === path) { unlinkSync(path); symlinkSync(join(outside, 'contract.json'), path, 'file'); }
    return st;
  };
  syncBuiltinESMExports();
  assert.deepEqual(contractEvidence(root, TEXT), { state: 'unreadable', link: CONTRACT_PATH });
});
