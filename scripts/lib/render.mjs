export function render(template, vars) {
  return template.replace(/\{\{(\w+)\}\}/g, (_, name) => {
    if (!(name in vars)) throw new Error(`render: no value for placeholder "${name}"`);
    return vars[name];
  });
}

// Coordinator finding (CRITICAL): uninstall-lib.mjs needs an independent,
// IN-FILE signal that a file genuinely came from this tool — a forged
// manifest entry (any repository write grants the ABILITY to add one: a
// contributor, a dependency's postinstall, a crafted repo, or an agent
// mid-session) must not be enough on its own to make a file deletable,
// because `classify`'s hash check only proves the content matches what
// the MANIFEST claims, never that harness-kit was the one who wrote it.
// `STAMP_MARKER` is that signal: every template this tool generates
// carries it (via `versionStamp`, below, or — for the one asset that
// embeds it directly rather than through this function,
// harness-redact.mjs's own proposal in propose.mjs — the identical
// literal text), and a user's own, unrelated file essentially never
// contains this exact phrase by coincidence. Exported so uninstall-lib.mjs
// checks the SAME string every generator writes, not a second guess at it.
export const STAMP_MARKER = 'Generated by harness-kit';

export function versionStamp(kitVersion, step, comment = '#') {
  return `${comment} ${STAMP_MARKER} ${kitVersion} (runbook step ${step}). Edit freely — harness-kit will report your changes rather than overwrite them.`;
}
