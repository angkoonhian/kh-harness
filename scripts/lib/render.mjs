import { readFileSync } from 'node:fs';
import { join } from 'node:path';

export function render(template, vars) {
  return template.replace(/\{\{(\w+)\}\}/g, (_, name) => {
    if (!(name in vars)) throw new Error(`render: no value for placeholder "${name}"`);
    return vars[name];
  });
}

// The in-file sign that a file came from this kit. The manifest is a file in
// the repository, so an entry in it can be forged, and `classify`'s hash check
// proves only that a file holds what the manifest claims, never that
// kh-harness wrote it. Every file a generator writes carries this text, and a
// file of the owner's essentially never does, so `uninstall` deletes and
// `apply` updates only a file that carries it.
export const STAMP_MARKER = 'Generated by kh-harness';

/** The stamp on a scaffold the owner is meant to write into: HANDOFF.md, the
 * registries, a path rule, the bootstrap script. */
export function versionStamp(kitVersion, step, comment = '#') {
  return `${comment} ${STAMP_MARKER} ${kitVersion} (runbook step ${step}). Edit freely — kh-harness will report your changes rather than overwrite them.`;
}

/** The stamp on a hook script or a module one loads, `what` naming it. These
 * are the kit's code: an edited copy is never overwritten, so it stops every
 * later update of the scripts that load it or that it loads, and
 * `P5.integrity` reports it. */
export function machineryStamp(kitVersion, what, comment = '#') {
  return `${comment} ${STAMP_MARKER} ${kitVersion} (${what}). Do not edit: kh-harness never overwrites an edited copy, so an edit stops its hook scripts being updated, and the integrity check reports it.`;
}

const STAMPED_VERSION = new RegExp(`${STAMP_MARKER} (\\d+\\.\\d+\\.\\d+(?:-[0-9A-Za-z.]{1,32})?) `);

/** The kit version the stamp in `text` names, or null when `text` carries no
 * stamp with a version-shaped token after it. The shape is checked because
 * the result is printed, and the file it is read from is the repository's. */
export function stampVersion(text) {
  return STAMPED_VERSION.exec(text)?.[1] ?? null;
}

/** True when the file at `relPath` under `root` carries the stamp. A missing
 * file, a directory and a read failure all answer false: a file that cannot
 * be read is not shown to be the kit's. */
export function carriesStamp(root, relPath) {
  try {
    return readFileSync(join(root, relPath), 'utf8').includes(STAMP_MARKER);
  } catch {
    return false;
  }
}
