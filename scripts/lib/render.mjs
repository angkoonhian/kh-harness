export function render(template, vars) {
  return template.replace(/\{\{(\w+)\}\}/g, (_, name) => {
    if (!(name in vars)) throw new Error(`render: no value for placeholder "${name}"`);
    return vars[name];
  });
}

export function versionStamp(kitVersion, step, comment = '#') {
  return `${comment} Generated by harness-kit ${kitVersion} (runbook step ${step}). Edit freely — harness-kit will report your changes rather than overwrite them.`;
}
