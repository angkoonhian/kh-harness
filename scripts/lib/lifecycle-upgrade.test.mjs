// scripts/lib/lifecycle-upgrade.test.mjs — upgrading a real 0.1.0 install,
// end to end through the CLIs of both kits. The 0.1.0 kit is the one this
// repository's history holds at KIT_0_1_0.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { appendFileSync, existsSync, mkdtempSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { DETECT, APPLY, UNINSTALL, git, kitAt, run, runEveryRegisteredHook, sandboxDataDir, settings } from './lifecycle-fixtures.mjs';
import { LINT_TOUCHED_PATH, REDACT_PATH, SESSION_LOG_PATH, TOOL_GATE_PATH, LOOP_WATCH_PATH } from './propose.mjs';
import { LOGGED_EVENTS } from '../../assets/scripts/session-log.mjs';

sandboxDataDir();

const KIT_0_1_0 = '681189d';
const old = kitAt(KIT_0_1_0);
const skip = old === null ? `commit ${KIT_0_1_0} is not in this checkout (a shallow clone); fetch the full history to run this` : false;

const CURRENT = JSON.parse(readFileSync(new URL('../../package.json', import.meta.url), 'utf8')).version;
const literal = text => new RegExp(text.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'));
const commit = (d, message) => {
  git(d, 'add', '-A');
  git(d, '-c', 'user.email=t@t', '-c', 'user.name=t', 'commit', '-q', '-m', message);
};

/** A repository with a lint script and a lockfile, holding a 0.1.0 install
 * whose `lint-touched.mjs` the owner has since edited, all committed. */
function editedInstall() {
  const d = mkdtempSync(join(tmpdir(), 'hk-upgrade-'));
  writeFileSync(join(d, 'package.json'), JSON.stringify({ name: 'app', scripts: { lint: 'node -e 0' } }));
  writeFileSync(join(d, 'package-lock.json'), '{}');
  // A source file, so the 0.1.0 kit detects a stack and installs the sensor.
  writeFileSync(join(d, 'index.js'), 'export const ok = true;\n');
  execFileSync('git', ['init', '-q', d]);
  git(d, 'checkout', '-q', '-b', 'chore/harness');
  git(d, 'remote', 'add', 'origin', 'https://example.invalid/kh-harness-fixture.git');
  commit(d, 'init');
  run(old.apply, d, '--yes');
  commit(d, 'install kh-harness 0.1.0');
  assert.ok(existsSync(join(d, LINT_TOUCHED_PATH)), 'the 0.1.0 kit installed the lint sensor');
  appendFileSync(join(d, LINT_TOUCHED_PATH), '// the owner\'s own line\n');
  commit(d, 'edit the lint sensor');
  return d;
}

const scriptsOnDisk = d => (existsSync(join(d, '.claude/scripts')) ? readdirSync(join(d, '.claude/scripts')).sort() : []);
const stampOf = (d, rel) => /Generated by kh-harness (\S+)/.exec(readFileSync(join(d, rel), 'utf8'))?.[1] ?? null;
const registeredScripts = d => Object.values(settings(d).hooks ?? {}).flat().flatMap(m => m.hooks ?? []).map(h => h.args?.[0] ?? h.command);
const checkOf = (d, id) => JSON.parse(run(DETECT, d, '--json')).checks.find(c => c.id === id);

function assertNoHookCrashes(d) {
  for (const h of runEveryRegisteredHook(d)) {
    assert.notEqual(h.status, 1, `${h.script} on ${h.event} exits ${h.status}: ${h.stderr}`);
    assert.doesNotMatch(h.stderr, /SyntaxError|ERR_MODULE_NOT_FOUND|does not provide an export/, `${h.script} on ${h.event}`);
  }
}

/** Each of the checks `ids` says absent, proposes nothing, and names the
 * kept file and both things the owner can do. */
function assertNamedAsHeld(d, ids) {
  for (const id of ids) {
    const c = checkOf(d, id);
    assert.equal(c.state, 'absent', id);
    assert.equal(c.proposal, null, `${id} proposes nothing`);
    const said = c.evidence.join('\n');
    assert.match(said, literal(LINT_TOUCHED_PATH), `${id} names the kept file`);
    assert.match(said, /restore/i, `${id} says the file can be restored`);
    assert.match(said, /stays? off/, `${id} says the hook otherwise stays off`);
  }
}

test('UPGRADE A: a 0.1.0 install with one edited script gets no 0.2.0 hook script beside it, and says why', { skip }, () => {
  const d = editedInstall();
  const before = scriptsOnDisk(d);
  const said = run(APPLY, d, '--yes');

  assert.deepEqual(scriptsOnDisk(d), before, 'no script is added beside the kept one');
  assert.match(said, /kh-harness keeps \.claude\/scripts\/lint-touched\.mjs \(edited since kh-harness wrote it\) as it is, and so writes and updates none of its hook scripts\./, 'apply says so itself');
  assert.equal(stampOf(d, REDACT_PATH), '0.1.0', 'the shared module is not updated without the script that imports it');
  for (const path of [SESSION_LOG_PATH, TOOL_GATE_PATH, LOOP_WATCH_PATH]) {
    assert.ok(!registeredScripts(d).some(s => s.includes(path)), `${path} is not registered`);
  }
  assertNoHookCrashes(d);
  assertNamedAsHeld(d, ['P5.sessionlog', 'P5.toolgate', 'P2.loopwatch']);
  assert.equal(checkOf(d, 'P2.sensor').state, 'declared', 'the 0.1.0 sensor still runs beside its 0.1.0 module');

  const skew = checkOf(d, 'P0.kitskew').evidence;
  assert.match(skew.join('\n'), /0\.1\.0/, 'the installed version is named');
  assert.match(skew.join('\n'), literal(CURRENT), 'the current version is named');
  assert.notEqual(skew[0], `kit ${CURRENT}`, 'the first line does not claim one version');
  assert.ok(skew.some(line => line.startsWith('held back') && line.includes(REDACT_PATH) && line.includes(LINT_TOUCHED_PATH)), 'the shared module is held back, with the file that holds it');

  // The owner restores the file kh-harness wrote; the upgrade then completes.
  git(d, 'checkout', 'HEAD~1', '--', LINT_TOUCHED_PATH);
  commit(d, 'restore the lint sensor');
  run(APPLY, d, '--yes');
  for (const name of scriptsOnDisk(d)) assert.equal(stampOf(d, `.claude/scripts/${name}`), CURRENT, name);
  for (const event of LOGGED_EVENTS) {
    assert.ok((settings(d).hooks[event] ?? []).some(m => m.hooks.some(h => h.args?.[0]?.endsWith(SESSION_LOG_PATH))), `the logging hook is on ${event}`);
  }
  assertNoHookCrashes(d);
  for (const id of ['P5.sessionlog', 'P5.toolgate', 'P2.loopwatch', 'P2.sensor', 'P0.kitskew']) assert.equal(checkOf(d, id).state, 'declared', id);
  assert.equal(checkOf(d, 'P0.kitskew').evidence[0], `kit ${CURRENT}`);
});

test('UPGRADE B: uninstall then apply puts no 0.2.0 module beside the edited 0.1.0 script uninstall kept', { skip }, () => {
  const d = editedInstall();
  run(UNINSTALL, d, '--yes');
  assert.deepEqual(scriptsOnDisk(d), ['lint-touched.mjs'], 'uninstall keeps the edited script alone');
  commit(d, 'uninstall');
  run(APPLY, d, '--yes');

  assert.deepEqual(scriptsOnDisk(d), ['lint-touched.mjs'], 'nothing is written beside it');
  assert.deepEqual(registeredScripts(d), [], 'no hook is registered');
  assertNamedAsHeld(d, ['P2.sensor', 'P5.sessionlog', 'P5.toolgate', 'P2.loopwatch', 'P4.sessionbrief']);

  git(d, 'checkout', 'HEAD~2', '--', LINT_TOUCHED_PATH);
  commit(d, 'restore the lint sensor');
  run(APPLY, d, '--yes');
  for (const name of scriptsOnDisk(d)) assert.equal(stampOf(d, `.claude/scripts/${name}`), CURRENT, name);
  assert.ok(scriptsOnDisk(d).includes('session-log.mjs'));
  assertNoHookCrashes(d);
  for (const id of ['P2.sensor', 'P5.sessionlog', 'P5.toolgate', 'P2.loopwatch', 'P4.sessionbrief']) assert.equal(checkOf(d, id).state, 'declared', id);
});
